"""WO-017 host side of the container worker (ADR-0013); standard library only.

Fixed script, pinned image, fixed flags, one read-only /input mount; no host
fallback. Worker output is never logged and leaves only as a parsed model. The
container's PID 1 is a timer that ends the run even if this process dies.
"""

from __future__ import annotations

import json
import math
import os
import re
import secrets
import selectors
import shutil
import subprocess
import tempfile
import threading
import time
from collections.abc import Mapping
from datetime import datetime

from idx_agent.analysis.protocol import WorkerOutputError, parse_worker_output
from idx_agent.domain.analysis import AnalysisSample
from idx_agent.domain.analysis_worker import (
    ANALYSIS_STDOUT_CAP,
    RENDER_STDOUT_CAP,
    STDERR_CAP,
    WALL_CLOCK_S,
    AnalysisRun,
    ExecutorConfig,
    WorkerRun,
    WorkerScript,
)

__all__ = [
    "ANALYSIS_STDOUT_CAP",
    "CONTAINER_GRACE_S",
    "RENDER_STDOUT_CAP",
    "STDERR_CAP",
    "WALL_CLOCK_S",
    "MAX_CONCURRENT",
    "MAX_CODE_CHARS",
    "available",
    "build_command",
    "run_analysis",
    "run_worker",
    "sweep_leftovers",
]

MAX_CONCURRENT = 2
MAX_CODE_CHARS = 20_000
TMPFS_SIZE = "16m"
MEMORY = "256m"
PIDS_LIMIT = 64
CPUS = "1"
NAME_PREFIX = "idx-analysis-"
SCRIPTS: frozenset[str] = frozenset({"bootstrap.py", "render.py"})
INPUT_FILES: frozenset[str] = frozenset({"sample.json", "analysis.py", "chart.json"})
SLOT_WAIT_S = 2.0
INSPECT_TIMEOUT_S = 5.0
REMOVE_TIMEOUT_S = 10.0
# PID 1 in the container: coreutils `timeout`, installed in the image unreadable to
# the worker user so model code cannot trace it, and as namespace init it ignores
# SIGKILL and SIGSTOP from inside. It outlives the host wall clock by the grace.
DEADLINE_BIN = "/opt/worker/deadline"
CONTAINER_GRACE_S = 5
# Older than this, an idx-analysis- container or input directory belongs to no run.
LEFTOVER_AGE_S = WALL_CLOCK_S + CONTAINER_GRACE_S + 30
_CHUNK = 64 * 1024
_NAME = re.compile(r"^idx-analysis-[0-9a-f]{16}$")
_OPERATOR_ENV = ("DOCKER_HOST", "DOCKER_CONTEXT", "DOCKER_CONFIG")

_slots = threading.BoundedSemaphore(MAX_CONCURRENT)


def _client_env() -> dict[str, str]:
    """PATH plus the operator's own docker settings; no model text, no secrets."""
    env = {"PATH": os.environ.get("PATH", "")}
    for key in _OPERATOR_ENV:
        value = os.environ.get(key)
        if value:
            env[key] = value
    return env


def new_name() -> str:
    return NAME_PREFIX + secrets.token_hex(8)


def container_deadline_s(config: ExecutorConfig) -> int:
    """Seconds after start at which the container's own timer kills the run."""
    return math.ceil(config.wall_clock_s) + CONTAINER_GRACE_S


def build_command(
    config: ExecutorConfig, name: str, input_dir: str, script: WorkerScript
) -> list[str]:
    """The exact docker argv for one run; pure, no I/O."""
    if config.docker is None:
        raise ValueError("docker client is unavailable")
    if script not in SCRIPTS:
        raise ValueError("unknown worker script")
    if (
        not name.startswith(NAME_PREFIX)
        or not name[len(NAME_PREFIX) :].isalnum()
        or not name.isascii()
    ):
        raise ValueError("container name is not generated by the executor")
    if not os.path.isabs(input_dir) or any(c in input_dir for c in ",=\n\r\x00"):
        raise ValueError("input directory is not usable as a mount source")
    return [
        config.docker,
        "run",
        "--rm",
        "--name",
        name,
        "--pull",
        "never",
        "--network",
        "none",
        "--read-only",
        "--tmpfs",
        f"/tmp:rw,noexec,nosuid,nodev,size={TMPFS_SIZE}",
        "--cap-drop",
        "ALL",
        "--security-opt",
        "no-new-privileges",
        "--user",
        "65534:65534",
        "--memory",
        MEMORY,
        "--memory-swap",
        MEMORY,
        "--pids-limit",
        str(PIDS_LIMIT),
        "--cpus",
        CPUS,
        "--ipc",
        "none",
        "--log-driver",
        "none",
        "--mount",
        f"type=bind,src={input_dir},dst=/input,readonly",
        "--stop-timeout",
        "1",
        config.image,
        DEADLINE_BIN,
        "-s",
        "KILL",
        str(container_deadline_s(config)),
        "python",
        "-I",
        f"/opt/worker/{script}",
    ]


def available(config: ExecutorConfig) -> bool:
    """True only when the client exists and the pinned image is already local."""
    if config.docker is None:
        return False
    try:
        done = subprocess.run(
            [config.docker, "image", "inspect", "--format", "{{.Id}}", config.image],
            stdin=subprocess.DEVNULL,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            env=_client_env(),
            timeout=INSPECT_TIMEOUT_S,
            check=False,
        )
    except (OSError, subprocess.SubprocessError):
        return False
    return done.returncode == 0


def _docker_quiet(config: ExecutorConfig, args: list[str], timeout: float) -> int:
    assert config.docker is not None
    return subprocess.run(
        [config.docker, *args],
        stdin=subprocess.DEVNULL,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        env=_client_env(),
        timeout=timeout,
        check=False,
    ).returncode


def _remove_container(config: ExecutorConfig, name: str) -> bool:
    """Force-remove the named container, retrying on error; True once confirmed gone.

    A create request the daemon finishes after this check is not seen here; that
    container is never started, and `sweep_leftovers` removes it later.
    """
    if config.docker is None:
        return False
    deadline = time.monotonic() + REMOVE_TIMEOUT_S
    for _ in range(3):
        try:
            remaining = deadline - time.monotonic()
            if remaining <= 0:
                return False
            _docker_quiet(config, ["rm", "-f", name], remaining)
            remaining = deadline - time.monotonic()
            if remaining <= 0:
                return False
            inspect = ["container", "inspect", "--format", "{{.Id}}", name]
            if _docker_quiet(config, inspect, remaining) != 0:
                return True
        except (OSError, subprocess.SubprocessError):
            continue
    return False


def _release_later(delay: float) -> None:
    """Free a slot once a container that could not be removed has hit its deadline."""
    timer = threading.Timer(max(delay, 0.0), _slots.release)
    timer.daemon = True
    timer.start()


def _stop_client(process: subprocess.Popen[bytes]) -> None:
    if process.poll() is None:
        try:
            process.kill()
        except OSError:
            pass
    try:
        process.wait(timeout=REMOVE_TIMEOUT_S)
    except subprocess.TimeoutExpired:
        pass


def _write_inputs(directory: str, files: Mapping[str, bytes]) -> None:
    for filename, content in files.items():
        path = os.path.join(directory, filename)
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o644)
        with os.fdopen(fd, "wb") as handle:
            handle.write(content)
        os.chmod(path, 0o644)


def _check_files(files: Mapping[str, bytes]) -> None:
    if not files or any(
        name not in INPUT_FILES or not isinstance(content, bytes)
        for name, content in files.items()
    ):
        raise ValueError("worker input files are not allowed")


def _collect(
    process: subprocess.Popen[bytes], deadline: float, stdout_cap: int, stderr_cap: int
) -> tuple[str, bytes]:
    """Read both pipes until EOF; return ("ok"|"timeout"|"output_too_large", out)."""
    assert process.stdout is not None and process.stderr is not None
    out = bytearray()
    err_bytes = 0
    with selectors.DefaultSelector() as selector:
        for stream in (process.stdout, process.stderr):
            os.set_blocking(stream.fileno(), False)
            selector.register(stream, selectors.EVENT_READ)
        while selector.get_map():
            remaining = deadline - time.monotonic()
            if remaining <= 0:
                return "timeout", b""
            for key, _ in selector.select(timeout=remaining):
                stream = key.fileobj
                try:
                    chunk = os.read(stream.fileno(), _CHUNK)
                except BlockingIOError:
                    continue
                if not chunk:
                    selector.unregister(stream)
                    continue
                if stream is process.stdout:
                    out += chunk
                    if len(out) > stdout_cap:
                        return "output_too_large", b""
                else:
                    err_bytes += len(chunk)  # counted and dropped, never kept
                    if err_bytes > stderr_cap:
                        return "output_too_large", b""
    remaining = deadline - time.monotonic()
    if remaining <= 0:
        return "timeout", b""
    try:
        process.wait(timeout=remaining)
    except subprocess.TimeoutExpired:
        return "timeout", b""
    return "ok", bytes(out)


def run_worker(
    config: ExecutorConfig,
    script: WorkerScript,
    files: Mapping[str, bytes],
    stdout_cap: int | None = None,
) -> WorkerRun:
    """Run one fixed script in the pinned image; always clean up the container."""
    started = time.monotonic()
    if script not in SCRIPTS:
        raise ValueError("unknown worker script")
    _check_files(files)
    limit = config.stdout_cap(script)
    if stdout_cap is not None:
        limit = min(limit, stdout_cap)

    def result(status: str, **extra: object) -> WorkerRun:
        return WorkerRun(status=status, duration_s=time.monotonic() - started, **extra)

    if not available(config):
        return result("unavailable")
    name = new_name()
    directory: str | None = None
    process: subprocess.Popen[bytes] | None = None
    launched = False  # set before Popen: an interrupt inside it may follow a start
    started_client = 0.0
    if not _slots.acquire(timeout=SLOT_WAIT_S):
        return result("busy")
    try:
        try:
            directory = tempfile.mkdtemp(prefix=NAME_PREFIX)
            os.chmod(directory, 0o755)
            _write_inputs(directory, files)
            argv = build_command(config, name, directory, script)
        except (OSError, ValueError):
            return result("failed")
        deadline = time.monotonic() + config.wall_clock_s
        started_client = time.monotonic()
        launched = True
        try:
            process = subprocess.Popen(
                argv,
                stdin=subprocess.DEVNULL,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                close_fds=True,
                env=_client_env(),
            )
        except OSError:
            launched = False  # the client never started, so no container exists
            return result("unavailable")
        status, out = _collect(process, deadline, limit, config.stderr_cap)
        if status != "ok":
            return result(status)
        code = process.returncode
        if code != 0:
            return result("failed", exit_code=code)
        return result("ok", stdout=out, exit_code=0)
    finally:
        _cleanup(config, name, directory, process, launched, started_client)


def _cleanup(
    config: ExecutorConfig,
    name: str,
    directory: str | None,
    process: subprocess.Popen[bytes] | None,
    launched: bool,
    started_client: float,
) -> None:
    """Every step runs even if an earlier one is interrupted; the slot is freed last.

    If the container cannot be confirmed gone, its slot stays taken until the
    container's own deadline has passed, so the two-run cap still holds.
    """
    removed = not launched  # no client started, so no container exists
    try:
        if process is not None:
            try:
                _stop_client(process)
            finally:
                for stream in (process.stdout, process.stderr):
                    if stream is not None:
                        stream.close()
    finally:
        try:
            if launched:
                removed = _remove_container(config, name)
        finally:
            try:
                if directory is not None:
                    shutil.rmtree(directory, ignore_errors=True)
            finally:
                if removed:
                    _slots.release()
                else:
                    _release_later(
                        started_client
                        + container_deadline_s(config)
                        + REMOVE_TIMEOUT_S
                        - time.monotonic()
                    )


def sweep_leftovers(
    config: ExecutorConfig,
    temp_root: str | None = None,
    min_age_s: float = LEFTOVER_AGE_S,
) -> int:
    """Remove idx-analysis- containers and input dirs that no live run can own.

    For tool-server start-up, after a killed process skipped its cleanup. Younger
    items may belong to another process's run and stay. Returns the count removed.
    """
    removed = 0
    now = time.time()
    if config.docker is not None:
        try:
            listing = subprocess.run(
                [
                    config.docker,
                    "ps",
                    "-a",
                    "--no-trunc",
                    "--filter",
                    "name=" + NAME_PREFIX,
                    "--format",
                    "{{.Names}}\t{{.CreatedAt}}",
                ],
                stdin=subprocess.DEVNULL,
                capture_output=True,
                text=True,
                env=_client_env(),
                timeout=INSPECT_TIMEOUT_S,
                check=False,
            )
        except (OSError, subprocess.SubprocessError):
            listing = None
        if listing is not None and listing.returncode == 0:
            for line in (listing.stdout or "").splitlines():
                name, _, created = line.partition("\t")
                if not _NAME.match(name):
                    continue
                try:  # e.g. "2026-10-28 01:40:58 +0000 UTC", in the client's zone
                    stamp = datetime.strptime(
                        created[:25], "%Y-%m-%d %H:%M:%S %z"
                    ).timestamp()
                except ValueError:
                    continue
                if now - stamp < min_age_s:
                    continue
                if _remove_container(config, name):
                    removed += 1
    root = temp_root if temp_root is not None else tempfile.gettempdir()
    try:
        entries = list(os.scandir(root))
    except OSError:
        entries = []
    for entry in entries:
        if not entry.name.startswith(NAME_PREFIX):
            continue
        try:
            info = entry.stat(follow_symlinks=False)
        except OSError:
            continue
        if (
            not entry.is_dir(follow_symlinks=False)
            or info.st_uid != os.getuid()
            or now - info.st_mtime < min_age_s
        ):
            continue
        shutil.rmtree(entry.path, ignore_errors=True)
        if not os.path.lexists(entry.path):
            removed += 1
    return removed


def _code_problem(code: object) -> str | None:
    if not isinstance(code, str):
        return "code_not_text"
    if len(code) > MAX_CODE_CHARS:
        return "code_too_long"
    if "\x00" in code:
        return "code_has_nul"
    try:
        code.encode("utf-8")
    except UnicodeEncodeError:
        return "code_not_utf8"
    return None


def run_analysis(
    config: ExecutorConfig, sample: AnalysisSample, code: str
) -> AnalysisRun:
    """Run model code over the sample's numeric rows; return parsed output only."""
    problem = _code_problem(code)
    if problem is not None:
        return AnalysisRun(status="invalid_code", reason=problem)
    files = {
        "sample.json": json.dumps(sample.worker_rows()).encode("utf-8"),
        "analysis.py": code.encode("utf-8"),
    }
    run = run_worker(config, "bootstrap.py", files, config.analysis_stdout_cap)
    if run.status != "ok":
        return AnalysisRun(status=run.status, duration_s=run.duration_s)
    assert run.stdout is not None
    try:
        output = parse_worker_output(run.stdout)
    except WorkerOutputError:
        return AnalysisRun(
            status="invalid_output", reason="output_refused", duration_s=run.duration_s
        )
    return AnalysisRun(status="ok", output=output, duration_s=run.duration_s)
